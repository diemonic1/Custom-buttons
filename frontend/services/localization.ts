import { useSyncExternalStore } from 'react';

export type Language = keyof typeof LOCALIZATION;
export type LocalizationKey = keyof (typeof LOCALIZATION)['English'];

// Steam API language names, see SteamClient.Settings.GetCurrentLanguage().
const STEAM_LANGUAGES: Record<string, Language> = {
	english: 'English',
	russian: 'Russian',
	schinese: 'ChineseSimplified',
	spanish: 'Spanish',
	latam: 'Spanish',
	brazilian: 'PortugueseBrazil',
	portuguese: 'PortugueseBrazil',
	german: 'German',
	french: 'French',
	japanese: 'Japanese',
	koreana: 'Korean',
	turkish: 'Turkish',
};

let current_language: Language = 'English';
const listeners = new Set<() => void>();

// The plugin follows the language of the Steam client; anything it has no
// translation for falls back to English.
export async function LoadSteamLanguage() {
	try {
		const steam_language = await SteamClient.Settings.GetCurrentLanguage();
		current_language = STEAM_LANGUAGES[steam_language] ?? 'English';
		listeners.forEach((listener) => listener());
	} catch (error) {
		console.error('[Custom-buttons] failed to get the Steam language', error);
	}
}

function subscribe(listener: () => void) {
	listeners.add(listener);
	return () => {
		listeners.delete(listener);
	};
}

export function useLanguage(): Language {
	return useSyncExternalStore(subscribe, () => current_language);
}

export function Localize(language: Language, key: LocalizationKey): string {
	return LOCALIZATION[language]?.[key] ?? LOCALIZATION.English[key] ?? key;
}

